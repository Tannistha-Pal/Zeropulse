CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'user',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    jwt_jti TEXT NOT NULL UNIQUE,
    ip_address INET,
    user_agent TEXT,
    device_id TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX IF NOT EXISTS sessions_user_created_at_idx
    ON sessions (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS sessions_active_expires_at_idx
    ON sessions (expires_at)
    WHERE is_active;

CREATE TABLE IF NOT EXISTS threat_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id TEXT UNIQUE,
    event_type TEXT NOT NULL,
    source TEXT,
    platform TEXT,
    subject JSONB,
    subject_jti TEXT,
    event_timestamp BIGINT,
    severity TEXT NOT NULL CHECK (severity IN ('low', 'medium', 'high')),
    risk_score INTEGER CHECK (risk_score BETWEEN 0 AND 100),
    processing_status TEXT NOT NULL,
    details JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS threat_events_created_at_idx
    ON threat_events (created_at DESC);
CREATE INDEX IF NOT EXISTS threat_events_subject_jti_idx
    ON threat_events (subject_jti);

CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    session_jti TEXT,
    action TEXT NOT NULL,
    event_type TEXT,
    source_ip INET,
    user_agent TEXT,
    details JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS audit_logs_user_created_at_idx
    ON audit_logs (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS audit_logs_session_jti_idx
    ON audit_logs (session_jti);
